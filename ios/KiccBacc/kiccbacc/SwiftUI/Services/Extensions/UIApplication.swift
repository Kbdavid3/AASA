import UIKit

extension UIApplication {
    func openSettings() {
        guard let url = URL(string: UIApplication.openSettingsURLString),
              UIApplication.shared.canOpenURL(url) else { return }
        UIApplication.shared.open(url) { status in
            print("Settings Opened \(status)")
        }
    }
}
